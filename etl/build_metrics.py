"""
RINK-OS Analytical Metrics Engine
---------------------------------
Reads shot_events.parquet, shifts.parquet, and players.parquet generated by
rink_os_etl.py to compute:
  1. Expected Goals (xG) per unblocked shot attempt (Fenwick)
  2. 5v5 WOWY (With Or Without You) line chemistry metrics
  3. Goaltender Goals Saved Above Expected (GSAx) & High-Danger SV%
"""

from __future__ import annotations

import json
import logging
from itertools import combinations
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

DATA_DIR = Path("./rink_os_data")

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)-8s | %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
)
logger = logging.getLogger("rink_os_metrics")


SHOT_TYPE_WEIGHTS = {
    "tip-in": 0.48,
    "deflected": 0.42,
    "wrap-around": 0.25,
    "backhand": 0.14,
    "snap": 0.12,
    "wrist": 0.08,
    "slap": -0.18,
}


def compute_xg(df: pd.DataFrame) -> pd.Series:
    """
    Compute Expected Goals (xG) for Fenwick events (goals, shots on goal, missed shots)
    using distance, shooting angle, shot type, and strength state.
    """
    dist = df["shot_distance_ft"].fillna(45.0).clip(lower=1.0, upper=100.0)
    angle = df["shot_angle_deg"].fillna(35.0).clip(lower=0.0, upper=90.0)
    shot_bonus = df["shot_type"].str.lower().map(SHOT_TYPE_WEIGHTS).fillna(0.0)

    # Logistic regression calibrated to NHL Fenwick scoring rates
    logit = (
        -0.82
        - 0.058 * dist
        - 0.019 * angle
        + shot_bonus
        + np.where(df["strength_state"] == "PP", 0.28, 0.0)
        + np.where(df["strength_state"] == "SH", 0.15, 0.0)
        + np.where(df["strength_state"] == "EN", 1.35, 0.0)
    )
    prob = 1.0 / (1.0 + np.exp(-logit))
    return np.where(df["is_fenwick"], np.round(prob, 4), 0.0)


def build_goaltender_summary(shots: pd.DataFrame, players: pd.DataFrame) -> list[dict[str, Any]]:
    """Aggregate Toronto goaltender GSAx, SV%, and High-Danger save metrics."""
    opp_sog = shots[(~shots["is_tor_event"]) & (shots["event_type"].isin({"goal", "shot-on-goal"}))].copy()
    opp_sog = opp_sog[opp_sog["goalie_id"].notna()]

    name_map = {
        row["player_id"]: f"{row['first_name']} {row['last_name']}"
        for _, row in players.iterrows()
    }

    results: list[dict[str, Any]] = []
    for goalie_id, grp in opp_sog.groupby("goalie_id"):
        gid = int(goalie_id)
        shots_against = len(grp)
        goals_against = int(grp["is_goal"].sum())
        xga = float(grp["xg"].sum())
        gsax = round(xga - goals_against, 2)
        sv_pct = round((shots_against - goals_against) / shots_against, 3) if shots_against else 0.0

        hd = grp[grp["xg"] >= 0.14]
        hd_sa = len(hd)
        hd_ga = int(hd["is_goal"].sum())
        hd_sv_pct = round((hd_sa - hd_ga) / hd_sa, 3) if hd_sa else 0.0

        results.append(
            {
                "goalie_id": gid,
                "goalie_name": name_map.get(gid, f"Goalie #{gid}"),
                "shots_against": shots_against,
                "goals_against": goals_against,
                "xga": round(xga, 2),
                "gsax": gsax,
                "sv_pct": sv_pct,
                "hd_shots_against": hd_sa,
                "hd_sv_pct": hd_sv_pct,
            }
        )

    return sorted(results, key=lambda x: x["shots_against"], reverse=True)


def build_5v5_pair_chemistry(shots: pd.DataFrame, players: pd.DataFrame, min_corsi: int = 25) -> list[dict[str, Any]]:
    """Compute 5v5 Corsi For % and xGF% for frequent Toronto skater pairs."""
    ev_shots = shots[shots["strength_state"] == "5v5"].copy()
    name_map = {
        row["player_id"]: f"{row['first_name']} {row['last_name']}"
        for _, row in players.iterrows()
    }
    pos_map = {row["player_id"]: row["position_code"] for _, row in players.iterrows()}

    pair_stats: dict[tuple[int, int], dict[str, float]] = {}

    for _, row in ev_shots.iterrows():
        skaters = [pid for pid in row["tor_skaters_on_ice"] if pos_map.get(pid) != "G"]
        is_for = bool(row["is_tor_event"])
        xg_val = float(row["xg"])

        for p1, p2 in combinations(sorted(skaters), 2):
            rec = pair_stats.setdefault((p1, p2), {"cf": 0.0, "ca": 0.0, "xgf": 0.0, "xga": 0.0})
            if is_for:
                rec["cf"] += 1.0
                rec["xgf"] += xg_val
            else:
                rec["ca"] += 1.0
                rec["xga"] += xg_val

    output: list[dict[str, Any]] = []
    for (p1, p2), st in pair_stats.items():
        total_c = st["cf"] + st["ca"]
        if total_c < min_corsi:
            continue
        total_xg = st["xgf"] + st["xga"]
        output.append(
            {
                "player_1_id": p1,
                "player_1_name": name_map.get(p1, str(p1)),
                "player_2_id": p2,
                "player_2_name": name_map.get(p2, str(p2)),
                "cf": int(st["cf"]),
                "ca": int(st["ca"]),
                "cf_pct": round((st["cf"] / total_c) * 100, 1),
                "xgf": round(st["xgf"], 2),
                "xga": round(st["xga"], 2),
                "xgf_pct": round((st["xgf"] / total_xg) * 100, 1) if total_xg > 0 else 50.0,
            }
        )

    return sorted(output, key=lambda x: x["cf"] + x["ca"], reverse=True)


def run_metrics(data_dir: Path = DATA_DIR) -> dict[str, Any]:
    shots = pd.read_parquet(data_dir / "shot_events.parquet")
    players = pd.read_parquet(data_dir / "players.parquet")

    shots["xg"] = compute_xg(shots)
    shots.to_parquet(data_dir / "shot_events.parquet", index=False)

    goalies = build_goaltender_summary(shots, players)
    chemistry = build_5v5_pair_chemistry(shots, players)

    summary = {
        "team_5v5_summary": {
            "cf": int(shots[(shots["strength_state"] == "5v5") & (shots["is_tor_event"])].shape[0]),
            "ca": int(shots[(shots["strength_state"] == "5v5") & (~shots["is_tor_event"])].shape[0]),
            "xgf": round(float(shots[(shots["strength_state"] == "5v5") & (shots["is_tor_event"])]["xg"].sum()), 2),
            "xga": round(float(shots[(shots["strength_state"] == "5v5") & (~shots["is_tor_event"])]["xg"].sum()), 2),
        },
        "goaltenders": goalies,
        "top_5v5_pairs": chemistry[:40],
    }

    out_path = data_dir / "rink_os_metrics.json"
    with out_path.open("w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, default=lambda v: int(v) if isinstance(v, np.integer) else float(v) if isinstance(v, np.floating) else str(v))

    logger.info("Computed xG, WOWY chemistry, and GSAx -> %s", out_path)
    return summary


if __name__ == "__main__":
    run_metrics()
